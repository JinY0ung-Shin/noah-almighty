/** The server's per-proposal raw source path: `raw/YYYY/MM/YYYY-MM-DD-<id8>.md` (UTC). */
export function teamRawPath(createdAtIso: string, id: string): string {
  const d = new Date(createdAtIso);
  const valid = !Number.isNaN(d.getTime());
  const iso = (valid ? d : new Date(0)).toISOString();
  const yyyy = iso.slice(0, 4);
  const mm = iso.slice(5, 7);
  const short = id.replace(/[^A-Za-z0-9]/g, "").slice(0, 8).toLowerCase() || "source";
  return `raw/${yyyy}/${mm}/${iso.slice(0, 10)}-${short}.md`;
}

