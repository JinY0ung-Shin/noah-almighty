/**
 * What a chat card renders (GET /api/team-brain/cards/:id) — only ever the
 * viewer's OWN card.
 *
 * Live card (`legacy: null`; kind `direct` or `policy`): `pages` is the diff,
 * `actions` say which of the two buttons work now, `provenance` drives the
 * 출처 정보 block.
 *
 * Legacy card (`legacy` set; kind `propose` or `review`): `pages` is `[]`,
 * `stale` is false, both `actions` are false and `provenance` is null — the
 * card is `proposal.title` plus `legacy.notice`.
 */
export interface TeamBrainCardView {
  proposal: TeamBrainProposal;
  /** Any page of the changeset changed since the draft (or a create target now exists) — apply is refused. */
  stale: boolean;
  /** direct cards: each page write, with its current content. policy cards: ONE entry, `POLICY.md`. */
  pages: TeamPageChangeView[];
  /**
   * Which buttons the viewer may press now. `apply` = 팀 브레인에 반영 / 팀 정책 반영:
   * a draft that is not stale, pressed by an active teammate (policy: an active
   * admin). `cancel` = 취소: any draft.
   */
  actions: { apply: boolean; cancel: boolean };
  /**
   * The card's own source provenance (출처 유형·출처·작성자·작성일): `editable` while the
   * drafter may still change it on the card (a direct draft with a source);
   * `issues` = what is missing or invalid — apply is refused until it is
   * empty. Null on cards without an own source.
   */
  provenance: { editable: boolean; issues: TeamProvenanceSlot[] } | null;
  /** Set on a card of the retired review queue; null on every live card. */
  legacy: TeamBrainLegacyCard | null;
}

/**
 * The card buttons whose press Noah REPORTS to the avatar that drafted the card
 * (server: `teamBrainCardPress.ts`): the confirm button (`apply`). 취소 is never
 * reported. (`submit` and `submit_all` went with the review queue; both names
 * are reserved.)
 */
export const TEAM_BRAIN_CARD_PRESS_ACTIONS = ["apply"] as const;
export type TeamBrainCardPressAction = (typeof TEAM_BRAIN_CARD_PRESS_ACTIONS)[number];

/** How every press report starts (agent-facing) — the standing prompt note names it. */
export const TEAM_BRAIN_CARD_PRESS_MARK = "[Team-brain card press";

/** What a press report needs to know about the card (a live `TeamBrainProposal` fits). */
export interface TeamBrainCardPressSubject {
  kind: TeamBrainLiveKind;
  title: string;
}

/** The Korean label ON the card's confirm button — the card and the press report share it. */
export function teamBrainCardButtonLabel(card: Pick<TeamBrainCardPressSubject, "kind">): string {
  return card.kind === "policy" ? "팀 정책 반영" : "팀 브레인에 반영";
}

const PRESS_BUBBLE_TITLE_MAX = 80;

/**
 * The chat bubble a reported press leaves in the presser's conversation
 * (Korean, user-facing): what THEY just did, shown and stored as their turn —
 * the model reads the server's English report instead. The client draws it
 * before the server answers, so both sides build it here.
 */
export function teamBrainCardPressBubble(card: TeamBrainCardPressSubject, ok: boolean): string {
  if (!ok) return `카드의 ‘${teamBrainCardButtonLabel(card)}’ 버튼을 눌렀지만 처리되지 않았습니다.`;
  const oneLine = card.title.replace(/\s+/g, " ").trim();
  const title = oneLine.length > PRESS_BUBBLE_TITLE_MAX ? `${oneLine.slice(0, PRESS_BUBBLE_TITLE_MAX)}…` : oneLine;
  const suffix = title ? `: ${title}` : ".";
  if (card.kind === "policy") return `팀 정책 변경을 반영했습니다${suffix}`;
  return `팀 브레인에 반영했습니다${suffix}`;
}

