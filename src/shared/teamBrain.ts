// ── Rows and views ───────────────────────────────────────────────────────────

/** A proposal row as the server and the card see it. */
export interface TeamBrainProposal {
  id: string;
  kind: TeamBrainProposalKind;
  status: TeamBrainProposalStatus;
  proposerUserId: string;
  proposerName: string;
  /** Null once the source conversation is gone. */
  conversationId: string | null;
  /**
   * propose: the raw source path it will be committed at (`teamRawPath`); a row
   * from before the schema still holds its old `wiki/…` note path.
   * review: the target's raw path. direct: its raw path, or "" for a
   * maintenance changeset (no new source).
   */
  path: string;
  op: TeamBrainOp;
  title: string;
  summary: string;
  /** propose / direct-with-source: the verbatim source text. review: "". Legacy rows: the old note. */
  content: string;
  /** Legacy single-note rows only (null otherwise). */
  baseBlob: string | null;
  /** propose / direct-with-source rows; null on review, maintenance and legacy rows. */
  intake: TeamBrainIntake | null;
  /** review (approve) / direct rows; null otherwise. */
  changeset: TeamBrainChangeset | null;
  /** review rows: the proposal being decided. */
  targetId: string | null;
  /** review rows: what pressing the button does. */
  decision: TeamBrainDecision | null;
  /** reject: the reason; ask: the questions (also copied onto the target while it is needs_info). */
  decisionReason: string | null;
  decidedBy: string | null;
  decidedByName: string | null;
  decidedAt: string | null;
  createdAt: string;
  updatedAt: string;
}

/** One page of a changeset as a card renders it (the client diffs before → after). */
export interface TeamPageChangeView {
  path: string;
  op: TeamBrainOp;
  /** From the new content's frontmatter ("" when unparsable). */
  title: string;
  type: TeamPageType | null;
  /** The page as committed NOW (null for a create, or when it is gone). */
  before: string | null;
  after: string;
  /** The page changed since the draft (or a create target now exists) — apply is refused. */
  stale: boolean;
}

/** What a chat card renders (GET /api/team-brain/cards/:id). */
export interface TeamBrainCardView {
  proposal: TeamBrainProposal;
  /** review cards: the proposal being decided (null otherwise). */
  target: TeamBrainProposal | null;
  /** Any page of the changeset is stale (or a legacy row's note changed) — apply/submit is refused. */
  stale: boolean;
  /** review (approve) / direct cards: each page write, with its current content. */
  pages: TeamPageChangeView[];
  /** Which buttons this viewer may press now. */
  actions: { submit: boolean; withdraw: boolean; apply: boolean; cancel: boolean };
}

/** Badge numbers (GET /api/team-brain/status). */
export interface TeamBrainStatus {
  /** My decided (approved / rejected / needs_info) proposals I have not looked at yet. */
  unseenResults: number;
  /** Admins only: proposals awaiting review (0 for everyone else). */
  pendingReview: number;
}

/** Admin backup state (GET /api/admin/team-brain). */
export interface TeamBrainBackupState {
  url: string | null;
  branch: string;
  /** Username of the admin whose git token pushes; null when unset. */
  adminName: string | null;
  lastOkAt: string | null;
  lastError: string | null;
  lastAttemptAt: string | null;
}
