// Team brain (팀 브레인) — shared client↔server vocabulary. ONE instance-wide
// LOCAL git vault that only Noah writes; teammates READ and SUBMIT SOURCES, an
// admin's avatar COMPILES them into wiki pages under a FIXED schema the server
// validates, and an admin decides. Every state change is a human button press on
// a chat card (the model only drafts). Design: docs/architecture/team-brain.md.
//
// Vault layout (schema v1, Karpathy-style LLM wiki):
//   SCHEMA.md                      fixed in code (teamBrainSchema.ts), agent-facing
//   raw/YYYY/MM/<date>-<id8>.md    one immutable source per approved submission
//   raw/legacy/…                   notes from before the schema (moved, never deleted)
//   wiki/<type folder>/<slug>.md   compiled pages, one fact one home
//   wiki/index.md                  catalog, regenerated by the SERVER from frontmatter
//   wiki/log.md                    append-only, one entry per commit, by the SERVER

/** Bump when SCHEMA.md / page validation changes; the vault migrates on boot. */
export const TEAM_BRAIN_SCHEMA_VERSION = 1;

/** propose = a teammate's source submission; direct = an admin's own changeset; review = an admin's decision on a proposal. */
export const TEAM_BRAIN_PROPOSAL_KINDS = ["propose", "direct", "review"] as const;
export type TeamBrainProposalKind = (typeof TEAM_BRAIN_PROPOSAL_KINDS)[number];

/**
 * propose: draft → pending (submitted) → approved | rejected | needs_info;
 *          needs_info → draft (the proposer answered, via their avatar) → pending …;
 *          draft/pending/needs_info → withdrawn; draft → expired.
 * direct / review: draft → applied | cancelled; draft → expired.
 */
export const TEAM_BRAIN_PROPOSAL_STATUSES = [
  "draft",
  "pending",
  "approved",
  "rejected",
  "needs_info",
  "withdrawn",
  "applied",
  "cancelled",
  "expired",
] as const;
export type TeamBrainProposalStatus = (typeof TEAM_BRAIN_PROPOSAL_STATUSES)[number];

/** No delete op — a wrong page is corrected with an update, a reversed decision is superseded (user decision 2026-11-06). */
export const TEAM_BRAIN_OPS = ["create", "update"] as const;
export type TeamBrainOp = (typeof TEAM_BRAIN_OPS)[number];

/** approve = commit the changeset; reject = decline with a reason; ask = send questions back to the proposer (보완 요청). */
export const TEAM_BRAIN_DECISIONS = ["approve", "reject", "ask"] as const;
export type TeamBrainDecision = (typeof TEAM_BRAIN_DECISIONS)[number];

/** Max source / page body (bytes, UTF-8). */
export const TEAM_BRAIN_MAX_CONTENT_BYTES = 64 * 1024;
/** Max pages one changeset may touch (Karpathy: one source touches 10–15 pages). */
export const TEAM_BRAIN_MAX_CHANGES = 15;
/** Max total bytes of one changeset's page contents. */
export const TEAM_BRAIN_MAX_CHANGESET_BYTES = 256 * 1024;
/** Max open (draft + pending + needs_info) proposals per user. */
export const TEAM_BRAIN_MAX_OPEN_PROPOSALS = 20;
/** A draft card nobody pressed expires after this long. */
export const TEAM_BRAIN_DRAFT_TTL_MS = 7 * 24 * 60 * 60 * 1000;

