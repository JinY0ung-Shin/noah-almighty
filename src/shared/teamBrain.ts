/** An answer meaning "the user does not know" — accepted, recorded as a gap. */
export const TEAM_INTAKE_UNKNOWN = "unknown";

export function isTeamIntakeUnknown(value: string): boolean {
  const v = value.trim().toLowerCase();
  return v === TEAM_INTAKE_UNKNOWN || v === "모름" || v === "알 수 없음" || v === "n/a";
}

